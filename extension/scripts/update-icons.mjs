import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { readFile, writeFile, mkdir } from "node:fs/promises";

class TechnologyIconVendor {
  static VERSION = "16.0.0";
  constructor() {
    this.root = new URL("../assets/technology-icons/", import.meta.url);
    this.aliases = { nextjs: "nextdotjs", vue: "vuedotjs", ghost: "ghost", angularjs: "angular", sveltekit: "svelte", alpine: "alpinedotjs", ember: "emberdotjs", backbone: "backbonedotjs", lit: "lit", moment: "momentdotjs", dayjs: "dayjs", chartjs: "chartdotjs", threejs: "threedotjs", mapbox: "mapbox", "google-maps": "googlemaps", fontawesome: "fontawesome", "google-fonts": "googlefonts", gtm: "googletagmanager", "google-analytics": "googleanalytics", clarity: "microsoft", fathom: "fathom", gsap: "gsap", requirejs: "requirejs", onetrust: "onetrust", cookiebot: "cookiebot", turnstile: "cloudflare", aos: null, videojs: null, materialize: null, newrelic: "newrelic", tawk: null, recaptcha: "google" };
    this.colors = { react: "00B9D8", nextjs: "111111", vue: "42B883", angular: "DD0031", wordpress: "21759B", jquery: "0769AD", bootstrap: "7952B3", drupal: "0678BE", nuxt: "00A86B", shopify: "7AB55C", woocommerce: "96588A", stripe: "635BFF", datadog: "632CA6", sentry: "362D59", gtm: "246FDB", "google-analytics": "E37400", cloudflare: "F38020", turnstile: "F38020", webpack: "1C78C0", vite: "646CFF", youtube: "FF0000", vimeo: "1AB7EA", leaflet: "199900", chartjs: "E8617C", d3: "F9A03C", lodash: "3492FF", axios: "5A29E4", fontawesome: "528DD7", webflow: "146EF5", astro: "D83A91", sveltekit: "FF3E00", htmx: "3366CC", gsap: "4B8718" };
  }

  async download(file) {
    const { stdout } = await promisify(execFile)(process.platform === "win32" ? "curl.exe" : "curl",
      ["-4", "--fail", "--silent", "--show-error", "--location", "--connect-timeout", "4", "--max-time", "12",
        `https://raw.githubusercontent.com/simple-icons/simple-icons/${TechnologyIconVendor.VERSION}/${file}`], { maxBuffer: 2000000 });
    return stdout;
  }

  async run() {
    await mkdir(this.root, { recursive: true });
    const catalog = JSON.parse(await readFile(new URL("../../shared/fingerprints.json", import.meta.url), "utf8"));
    const queue = [...catalog.technologies];
    const icons = {};
    const missing = [];
    await Promise.all(Array.from({ length: 8 }, async () => {
      while (queue.length) {
        const { id } = queue.shift();
        const slug = Object.hasOwn(this.aliases, id) ? this.aliases[id] : id.replaceAll("-", "");
        if (!slug) { missing.push(id); continue; }
        try {
          let svg = await this.download(`icons/${slug}.svg`);
          if (!svg.startsWith("<svg ") || /<script|\bon\w+=|(?:href|src)=|<!/i.test(svg)) throw new Error("Unsafe SVG");
          svg = svg.replace("<svg ", `<svg fill="#${this.colors[id] ?? "325970"}" `);
          await writeFile(new URL(`${id}.svg`, this.root), svg + "\n");
          icons[id] = `${id}.svg`;
        } catch {
          try { await readFile(new URL(`${id}.svg`, this.root)); icons[id] = `${id}.svg`; }
          catch { missing.push(id); }
        }
      }
    }));
    if (Object.keys(icons).length < 30) throw new Error("Too few icons downloaded. Check connectivity; the existing manifest was preserved.");
    const sorted = Object.fromEntries(Object.entries(icons).sort(([a], [b]) => a.localeCompare(b)));
    await writeFile(new URL("icons.js", this.root), `// Simple Icons ${TechnologyIconVendor.VERSION}, CC0-1.0. Generated by scripts/update-icons.mjs.\nexport const technologyIcons = ${JSON.stringify(sorted, null, 2)};\n`);
    const license = await this.download("LICENSE.md");
    await writeFile(new URL("LICENSE.md", this.root), license);
    console.log(`${Object.keys(icons).length} local brand icons. Generic fallback: ${missing.sort().join(", ")}.`);
  }
}

await new TechnologyIconVendor().run();
